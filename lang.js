/**
 * Apply the selected language across all elements with data-i18n attributes
 * English is permanently enforced as the sole default language.
 * @param {string} [_lang] - Optional language parameter, always defaults to 'en'
 */
function setLanguage(_lang) {
  const lang = "en";
  const selectedStrings = translations[lang] || {};

  // Update text content
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (selectedStrings[key]) {
      el.textContent = selectedStrings[key];
    }
  });

  // Update placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (selectedStrings[key]) {
      el.setAttribute("placeholder", selectedStrings[key]);
    }
  });

  // Enforce English preference in localStorage
  try {
    localStorage.setItem("preferred_language", "en");
  } catch (e) {
    // Ignore storage errors
  }

  // Set HTML lang attribute to English
  document.documentElement.lang = "en";

  // Notify listeners that English is active
  try {
    window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang: "en" } }));
  } catch (e) {
    // Fallback for older browsers
  }
}

// Initialize on page load: enforce English as the sole default language
document.addEventListener("DOMContentLoaded", () => {
  setLanguage("en");
});
